/**
 * Get localized name for an ingredient
 */
export function getLocalizedIngredientName(
  ingredient: { name: string; nameTa?: string; nameHi?: string },
  language: 'en' | 'ta' | 'hi'
): string {
  if (language === 'ta') {
    if (ingredient.nameTa) return ingredient.nameTa;
    const match = INGREDIENT_TRANSLATIONS[ingredient.name];
    if (match?.ta) return match.ta;
  }
  if (language === 'hi') {
    if (ingredient.nameHi) return ingredient.nameHi;
    const match = INGREDIENT_TRANSLATIONS[ingredient.name];
    if (match?.hi) return match.hi;
  }
  return ingredient.name;
}
